# The FEC's own 2026 summary for Enoch has contributions larger than total receipts.
ODD = {"OH-H-08:enoch": ("H8OH08097", "The FEC’s 2026 summary for this candidate doesn’t add up (its contributions are larger than its total receipts), so its figures aren’t shown here. The FEC page has them.")}

names = {c["id"]: c["name"] for r in json.loads((Path(__file__).resolve().parents[2] / "data" / "races.json").read_text(encoding="utf-8"))["races"] for c in r["candidates"]}


def fin(note, url):
    return {"note": note, "url": url, "source": "FEC", "asOf": CHECKED, "parts": {}}


def page(fec_id):
    return f"https://www.fec.gov/data/candidate/{fec_id}/?cycle=2026&election_full=true"


notes = {}
for cid, fec_id in NO_REPORT:
    notes[cid] = fin("The FEC lists this candidate but had no financial report for the 2026 campaign when checked on Oct. 26, 2026. New reports can take a few days to appear.", page(fec_id))
for cid in NOT_FOUND:
    notes[cid] = fin("No FEC record for this candidate in this district turned up in a search on Oct. 26, 2026. Candidates who raise or spend less than $5,000 don’t have to register with the FEC.",
                     "https://www.fec.gov/data/candidates/?q=" + urllib.parse.quote(names.get(cid, cid.split(":")[1])))
for cid, (fec_id, text) in ODD.items():
    notes[cid] = fin(text, page(fec_id))

races = {}
for cid, f in sorted(notes.items()):
    races.setdefault(cid.split(":")[0], []).append({"id": cid, "finance": f})
write("data/research/fec_notes.json", [{"id": rid, "financeOnly": True, "candidates": cs} for rid, cs in races.items()],
      "Notes for House candidates with no FEC figures to show, from fec.gov searches on Oct. 26, 2026.", updated=CHECKED)
